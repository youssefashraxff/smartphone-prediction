# LIBRARIES
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import joblib

# Models
from xgboost import XGBClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.svm import SVC

# Preprocessing & Metrics
from sklearn.preprocessing import LabelEncoder, StandardScaler, OneHotEncoder
from sklearn.pipeline import Pipeline
from sklearn.model_selection import train_test_split, GridSearchCV
from sklearn.metrics import (accuracy_score,
                             f1_score, confusion_matrix, roc_curve, roc_auc_score)

# LOAD DATA
if __name__ == "__main__":
    train_df = pd.read_csv('./data/train.csv')
    test_df = pd.read_csv('./data/test.csv')

    print(f"Train Shape: {train_df.shape}")
    print(f"Test Shape:  {test_df.shape}")
    print(f"\nTarget Distribution (Train):\n{train_df['price'].value_counts()}")


    # PREPROCESSING


    # Remove duplicates
    duplicates_count = train_df.duplicated().sum()
    train_df = train_df.drop_duplicates().reset_index(drop=True)
    if duplicates_count > 0:
        print(f"Removed {duplicates_count} duplicate rows")

        # Check for null values
    null_count = train_df.isnull().sum()
    print(f"Null values: {null_count}")


    # CLEANING (Text & Outliers)

    # 1. Standardize Text Columns
    text_cols = ['brand', 'os_name']
    for df in [train_df, test_df]:
        for col in text_cols:
            if col in df.columns:
                df[col] = df[col].str.title()

    # 2. Handle Outliers (Clipping method)
    # We clip numerical columns to the 1.5*IQR range to handle extreme values
    numerical_cols = train_df.select_dtypes(include=[np.number]).columns.tolist()
    if 'price' in numerical_cols: numerical_cols.remove('price')

    for col in numerical_cols:
        Q1 = train_df[col].quantile(0.25)
        Q3 = train_df[col].quantile(0.75)
        IQR = Q3 - Q1
        lower = Q1 - 1.5 * IQR
        upper = Q3 + 1.5 * IQR

        train_df[col] = train_df[col].clip(lower=lower, upper=upper)
        test_df[col] = test_df[col].clip(lower=lower, upper=upper)

    print("✅ Text standardized and outliers clipped.")


    #  SEPARATION & ENCODING


    y_train_full = train_df['price']
    X_train_full = train_df.drop('price', axis=1)

    y_test_final = test_df['price']
    X_test_final = test_df.drop('price', axis=1)

    # 2. Encode Target (Price -> 0/1)
    le = LabelEncoder()
    y_train_full_enc = le.fit_transform(y_train_full)
    y_test_final_enc = le.transform(y_test_final)

    # 3. One-Hot Encoding for Categorical Features
    categorical_cols = X_train_full.select_dtypes(include=['object']).columns.tolist()
    numerical_cols = X_train_full.select_dtypes(include=[np.number]).columns.tolist()

    ohe = OneHotEncoder(handle_unknown='ignore', sparse_output=False)

    # Fit on TRAIN, Transform BOTH
    X_train_cat = ohe.fit_transform(X_train_full[categorical_cols])
    X_test_cat = ohe.transform(X_test_final[categorical_cols])

    # 4. Reconstruct DataFrames (Crucial step to keep column names)
    cat_names = ohe.get_feature_names_out(categorical_cols)
    final_names = numerical_cols + cat_names.tolist()

    X_train_enc = pd.DataFrame(
        np.hstack([X_train_full[numerical_cols].values, X_train_cat]),
        columns=final_names
    )

    X_test_enc = pd.DataFrame(
        np.hstack([X_test_final[numerical_cols].values, X_test_cat]),
        columns=final_names
    )

    print("✅ Data Encoded. Categorical columns converted to One-Hot vectors.")


    # FEATURE ENGINEERING (PPI)

    def calculate_ppi(width, height, screen_size):

        diagonal = np.hypot(width, height)
        ppi = diagonal / screen_size.replace(0, np.nan)
        return ppi.fillna(0)


    for df in [X_train_enc, X_test_enc]:
        df['PPI'] = calculate_ppi(df['Resolution_Width'], df['Resolution_Height'], df['Screen_Size'])
        df.drop(columns=['Resolution_Width', 'Resolution_Height', 'Screen_Size'], inplace=True)

    print("✅ PPI Feature Created. Original resolution columns dropped.")


    # SPLITTING & FEATURE SELECTION

    from sklearn.feature_selection import SelectFromModel

    # 1. Split Training Data -> Train (80%) + Validation (20%)
    X_train, X_val, y_train, y_val = train_test_split(
        X_train_enc, y_train_full_enc,
        test_size=0.2, random_state=42, stratify=y_train_full_enc
    )


    print("Selecting Top 10 Features...")
    selector = RandomForestClassifier(n_estimators=100, random_state=42)
    selector.fit(X_train, y_train)

    # Get top 10 features
    importances = pd.Series(selector.feature_importances_, index=X_train.columns)
    top_10_features = importances.sort_values(ascending=False).head(10).index.tolist()

    print(f"\n🏆 Selected Features: {top_10_features}")

    # 3. Subset the Data (Keep only the Top 10)
    X_train_sel = X_train[top_10_features]
    X_val_sel = X_val[top_10_features]
    X_test_sel = X_test_enc[top_10_features]

    print("✅ Data Subsetted. Ready for Pipeline.")


    # SCALING

    # We scale only the selected 10 features
    scaler = StandardScaler()

    # Fit on Train, Transform Validation & Test
    X_train_ready = scaler.fit_transform(X_train_sel)
    X_val_ready = scaler.transform(X_val_sel)
    X_test_ready = scaler.transform(X_test_sel) # External Test Set

    print(f"✅ Data Scaled. Ready for training.")
    print(f"Train Shape: {X_train_ready.shape}")
    print(f"Val Shape:   {X_val_ready.shape}")
    print(f"Test Shape:  {X_test_ready.shape}")


    # BASELINE MODELS (With Pipeline)


    def evaluate_model(y_true, y_pred, model_name):
        return {
            'Model': model_name,
            'Accuracy': accuracy_score(y_true, y_pred),
            'F1-Score': f1_score(y_true, y_pred, average='binary')
        }

    # Define Pipelines: Scaler -> Model
    pipelines_config = {
        'Random Forest': Pipeline([
            ('scaler', StandardScaler()),
            ('model', RandomForestClassifier(random_state=42, n_jobs=-1))
        ]),
        'Logistic Regression': Pipeline([
            ('scaler', StandardScaler()),
            ('model', LogisticRegression(random_state=42, max_iter=1000))
        ]),
        'SVM': Pipeline([
            ('scaler', StandardScaler()),
            ('model', SVC(random_state=42, probability=True))
        ]),
        'XGBoost': Pipeline([
            ('scaler', StandardScaler()),
            ('model', XGBClassifier(random_state=42, eval_metric='logloss'))
        ])
    }

    baseline_results = []
    print("Training Baseline Pipelines...")

    for name, pipe in pipelines_config.items():
        # Fit the ENTIRE pipeline (It scales automatically)
        pipe.fit(X_train_sel, y_train)

        # Predict (It scales automatically)
        y_val_pred = pipe.predict(X_val_sel)

        baseline_results.append(evaluate_model(y_val, y_val_pred, name))


    print("\n📊 Baseline Leaderboard (Validation Set):")
    print(pd.DataFrame(baseline_results).sort_values(by='F1-Score', ascending=False))


    # HYPERPARAMETER TUNING (With Pipeline)

    print("Tuning Hyperparameters with Pipelines...")

    grids = {
        'Random Forest': (
            pipelines_config['Random Forest'],
            {'model__n_estimators': [100, 200], 'model__max_depth': [10, 20]}
        ),
        'SVM': (
            pipelines_config['SVM'],
            {'model__C': [0.1, 1, 10], 'model__kernel': ['rbf', 'linear']}
        ),
        'XGBoost': (
            pipelines_config['XGBoost'],
            {'model__n_estimators': [100, 200], 'model__learning_rate': [0.01, 0.1]}
        )
    }

    tuned_results = []
    tuned_pipelines = {}

    for name, (pipe, params) in grids.items():
        print(f"--> Tuning {name}...")

        # GridSearch manages the Pipeline
        grid = GridSearchCV(pipe, params, cv=3, scoring='f1', n_jobs=-1)
        grid.fit(X_train_sel, y_train)

        best_pipe = grid.best_estimator_
        y_val_pred = best_pipe.predict(X_val_sel)

        metrics = evaluate_model(y_val, y_val_pred, name)
        metrics['Best Params'] = grid.best_params_
        tuned_results.append(metrics)
        tuned_pipelines[name] = best_pipe

    print("\n📊 Tuned Leaderboard (Validation Set):")
    tuned_df = pd.DataFrame(tuned_results)
    print(tuned_df[['Model', 'Accuracy', 'F1-Score']].sort_values(by='F1-Score', ascending=False))


    # FINAL TEST

    # 1. Pick the Winner
    best_row = tuned_df.sort_values(by='F1-Score', ascending=False).iloc[0]
    best_model_name = best_row['Model']
    best_model = tuned_pipelines[best_model_name]

    print(f"🏆 Champion Model: {best_model_name}")

    # 2. Predict on EXTERNAL Test Data (test.csv)
    # This is data the model has NEVER seen before (not even in validation)
    y_test_pred = best_model.predict(X_test_ready)
    final_acc = accuracy_score(y_test_final_enc, y_test_pred)

    print(f"✅ Final Test Accuracy: {final_acc:.4f}")

    # 3. Visuals
    plt.figure(figsize=(12, 5))

    # Confusion Matrix
    plt.subplot(1, 2, 1)
    cm = confusion_matrix(y_test_final_enc, y_test_pred)
    sns.heatmap(cm, annot=True, fmt='d', cmap='Blues')
    plt.title(f'Confusion Matrix ({best_model_name})')
    plt.xlabel('Predicted')
    plt.ylabel('Actual')

    # ROC Curve
    plt.subplot(1, 2, 2)
    if hasattr(best_model, "predict_proba"):
        y_probs = best_model.predict_proba(X_test_ready)[:, 1]
        fpr, tpr, _ = roc_curve(y_test_final_enc, y_probs)
        auc_score = roc_auc_score(y_test_final_enc, y_probs)
        plt.plot(fpr, tpr, label=f'AUC = {auc_score:.3f}')
        plt.plot([0, 1], [0, 1], 'k--')
        plt.title('ROC Curve')
        plt.legend()

    plt.tight_layout()
    plt.show()


    # OVERFITTING CHECK

    train_acc = best_model.score(X_train_ready, y_train)
    test_acc = accuracy_score(y_test_final_enc, y_test_pred)
    gap = train_acc - test_acc

    print(f"Training Accuracy: {train_acc:.4f}")
    print(f"Testing Accuracy:  {test_acc:.4f}")
    print(f"Gap:               {gap:.4f}")

    if gap > 0.10:
        print("⚠️ Warning: Model might be overfitting (Gap > 10%)")
    else:
        print("✅ Success: Model is generalizing well (Gap < 10%)")


    # SAVE FOR DEPLOYMENT (Clean Pipeline)

    print("Saving pipeline for Streamlit app...")

    # Pick Winner
    best_row = tuned_df.sort_values(by='F1-Score', ascending=False).iloc[0]
    best_model_name = best_row['Model']
    best_pipeline = tuned_pipelines[best_model_name]

    artifacts = {
        'pipeline': best_pipeline,   # Contains BOTH Scaler and Model
        'encoder': ohe,              # For Categorical Features (if any)
        'features': top_10_features, # The input list
        'label_encoder': le          # Target mapping
    }

    joblib.dump(artifacts, 'deployment_pipeline.pkl')
    print(f"✅ Saved 'deployment_pipeline.pkl' (Winner: {best_model_name})")